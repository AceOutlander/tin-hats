/**
 * Campaign map outline data: hand-simplified coastlines of western Europe and
 * North Africa as lon/lat rings, the labels printed on the map, the projection,
 * and the layout numbers the campaign screen uses.
 *
 * Pure data and maths (no DOM): the campaign screen draws it with Canvas 2D.
 * Rings are flat [lon, lat, lon, lat, ...] arrays in degrees and are closed
 * implicitly. Rings that reach the map edge run outside it and are clipped by
 * the canvas. Accuracy is "recognisable at phone size", not survey grade.
 */

export interface MapBounds {
  lonMin: number;
  lonMax: number;
  latMin: number;
  latMax: number;
}

export interface MapShape {
  name: string;
  /** Flat lon/lat pairs. */
  pts: readonly number[];
}

export interface MapLabel {
  text: string;
  lon: number;
  lat: number;
  kind: 'country' | 'region' | 'sea';
  /** Rotation in degrees, clockwise. */
  angle?: number;
}

/** The window of the world the campaign map shows. */
export const MAP_BOUNDS: MapBounds = { lonMin: -11.5, lonMax: 34, latMin: 28.5, latMax: 59.5 };

/** Layout numbers for the campaign screen (CSS px unless noted). */
export const CAMPAIGN_MAP_VIEW = {
  /** The map is never drawn narrower than this, so it pans on small phones. */
  minWidthPx: 620,
  /** Minimum distance between two pin centres after de-clustering (touch targets are 48 px). */
  pinSeparationPx: 50,
  /** Pins stay at least this far inside the map edge. */
  pinMarginPx: 30,
  /** Relaxation passes used to push clustered pins apart. */
  pinRelaxIterations: 240,
  /** How strongly a displaced pin is pulled back toward its true position each pass (0..1). */
  pinSpring: 0.04,
  /** Degrees between graticule lines. */
  graticuleStepDeg: 5,
  /** A pointer must travel this far before a touch on the map becomes a pan. */
  dragThresholdPx: 7,
  /** Canvas backing-store scale is capped here. */
  maxPixelRatio: 2,
} as const;

const DEG = Math.PI / 180;

function mercator(latDeg: number): number {
  return Math.log(Math.tan(Math.PI / 4 + (latDeg * DEG) / 2));
}

const MERC_TOP = mercator(MAP_BOUNDS.latMax);
const MERC_BOTTOM = mercator(MAP_BOUNDS.latMin);
const LON_SPAN_RAD = (MAP_BOUNDS.lonMax - MAP_BOUNDS.lonMin) * DEG;

/** Width divided by height of the projected map. */
export const MAP_ASPECT = LON_SPAN_RAD / (MERC_TOP - MERC_BOTTOM);

/** Longitude to a 0..1 fraction of the map width (may fall outside for off-map points). */
export function mapX(lon: number): number {
  return (lon - MAP_BOUNDS.lonMin) / (MAP_BOUNDS.lonMax - MAP_BOUNDS.lonMin);
}

/** Latitude to a 0..1 fraction of the map height, 0 at the top (Mercator, so shapes look familiar). */
export function mapY(lat: number): number {
  const clamped = lat > 80 ? 80 : lat < -80 ? -80 : lat;
  return (MERC_TOP - mercator(clamped)) / (MERC_TOP - MERC_BOTTOM);
}

